// tlsPCValue decodes the PC-value format shared by object files and pclntab.
func tlsPCValue(t *testing.T, data []byte, target int64) int32 {
	t.Helper()
	value, pc := int32(-1), int64(0)
	for len(data) != 0 {
		delta, n := binary.Uvarint(data)
		if n <= 0 {
			t.Fatal("invalid PC-value delta")
		}
		data = data[n:]
		if delta == 0 && pc != 0 {
			break
		}
		value += int32(delta>>1) ^ -int32(delta&1)
		dpc, n := binary.Uvarint(data)
		if n <= 0 {
			t.Fatal("invalid PC delta")
		}
		data = data[n:]
		pc += int64(dpc) // AMD64's PCQuantum is one byte.
		if target < pc {
			return value
		}
	}
	t.Fatalf("no PC-value entry for pc=%d", target)
	return 0
}

// Exercise the full object pipeline, including the PCSP and unsafe-point
// tables consumed by the linker, rather than checking just generated bytes.
func TestOpenHarmonyTLSDescriptorMetadata(t *testing.T) {
	saved := isOpenharmony
	isOpenharmony = true
	t.Cleanup(func() { isOpenharmony = saved })

	for _, move := range []obj.As{AMOVQ, AMOVL} {
		for _, dst := range []int16{REG_AX, REG_CX, REG_R14} {
			for _, store := range []bool{false, true} {
				for _, priorUnsafe := range []int64{abi.UnsafePointSafe, abi.UnsafePointUnsafe, abi.UnsafePointRestart1} {
					t.Run(fmt.Sprintf("%s/%s/store=%v/unsafe=%d", move, rconv(int(dst)), store, priorUnsafe), func(t *testing.T) {
						ctxt := obj.Linknew(&Linkamd64)
						ctxt.Headtype = objabi.Hlinux
						ctxt.Flag_shared = true
						ctxt.Pkgpath = "tlsdesctest"
						ctxt.DiagFunc = func(format string, args ...any) { t.Fatalf(format, args...) }
						pos := ctxt.PosTable.XPos(src.MakePos(src.NewFileBase("tlsdesc.s", "tlsdesc.s"), 1, 0))
						sym := ctxt.Lookup("tlsdesctest.load")
						ctxt.InitTextSym(sym, obj.NOSPLIT|obj.NOFRAME, pos)
						p := ctxt.NewProg()
						p.As, p.Pos = obj.ATEXT, pos
						p.From = obj.Addr{Type: obj.TYPE_MEM, Name: obj.NAME_EXTERN, Sym: sym}
						p.To = obj.Addr{Type: obj.TYPE_TEXTSIZE, Val: int32(0)}
						sym.Func().Text = p
						first := p

						p = obj.Appendp(p, ctxt.NewProg)
						p.As = obj.APCDATA
						p.From = obj.Addr{Type: obj.TYPE_CONST, Offset: abi.PCDATA_UnsafePoint}
						p.To = obj.Addr{Type: obj.TYPE_CONST, Offset: priorUnsafe}

						p = obj.Appendp(p, ctxt.NewProg)
						p.As = move
						p.From = obj.Addr{Type: obj.TYPE_REG, Reg: REG_TLS}
						p.To = obj.Addr{Type: obj.TYPE_REG, Reg: dst}

						p = obj.Appendp(p, ctxt.NewProg)
						p.As = AMOVQ
						p.From = obj.Addr{Type: obj.TYPE_MEM, Reg: dst, Index: REG_TLS, Scale: 1}
						p.To = obj.Addr{Type: obj.TYPE_REG, Reg: dst}
						if store {
							p.From, p.To = p.To, p.From
						}
						loadG := p

						p = obj.Appendp(p, ctxt.NewProg)
						p.As = AMOVQ
						p.From = obj.Addr{Type: obj.TYPE_REG, Reg: REG_DX}
						p.To = obj.Addr{Type: obj.TYPE_REG, Reg: REG_DX}
						after := p
						p = obj.Appendp(p, ctxt.NewProg)
						p.As = obj.ARET

						obj.Flushplist(ctxt, &obj.Plist{Firstpc: first}, ctxt.NewProg)

						sp := int32(0)
						pushes, pops, descriptors := 0, 0, 0
						for p := sym.Func().Text; p != nil; p = p.Link {
							if p.As == APUSHQ {
								pushes++
								if p.From.Reg != REG_AX || p.Spadj != 8 {
									t.Fatalf("invalid descriptor save: %v spadj=%d", p, p.Spadj)
								}
							}
							if p.As == APOPQ {
								pops++
								if p.To.Reg != REG_AX || p.Spadj != -8 {
									t.Fatalf("invalid descriptor restore: %v spadj=%d", p, p.Spadj)
								}
							}
							if p.As == AMOVQ && p.From.Reg == REG_TLS {
								descriptors++
								if p.To.Reg != REG_AX || p.Isize != 9 {
									t.Fatalf("descriptor must be only LEA+CALL into AX: %v size=%d", p, p.Isize)
								}
								want := []byte{0x48, 0x8d, 0x05, 0, 0, 0, 0, 0xff, 0x10}
								if !bytes.Equal(sym.P[p.Pc:p.Pc+9], want) {
									t.Fatalf("descriptor bytes = %x, want %x", sym.P[p.Pc:p.Pc+9], want)
								}
							}
							// Check every emitted byte, including both instructions
							// within the descriptor Prog and the POP instruction.
							for pc := p.Pc; pc < p.Pc+int64(p.Isize); pc++ {
								if got := tlsPCValue(t, sym.Func().Pcln.Pcsp.P, pc); got != sp {
									t.Errorf("pc=%d (%v): PCSP=%d, want %d", pc, p, got, sp)
								}
								if p.Mark&tlsDescUnsafe != 0 || p == loadG {
									if got := tlsPCValue(t, sym.Func().Pcln.Pcdata[abi.PCDATA_UnsafePoint].P, pc); got != abi.UnsafePointUnsafe {
										t.Errorf("pc=%d (%v): unsafe=%d, want UnsafePointUnsafe", pc, p, got)
									}
								}
							}
							sp += p.Spadj
						}
						wantSaves := 1
						if dst == REG_AX {
							wantSaves = 0
						}
						if pushes != wantSaves || pops != wantSaves || descriptors != 1 || sp != 0 {
							t.Fatalf("unbalanced lowering: pushes=%d pops=%d descriptors=%d sp=%d", pushes, pops, descriptors, sp)
						}
						if got := tlsPCValue(t, sym.Func().Pcln.Pcdata[abi.PCDATA_UnsafePoint].P, after.Pc); got != int32(priorUnsafe) {
							t.Errorf("unsafe state after TLS = %d, want %d", got, priorUnsafe)
						}
						if len(sym.R) != 1 || sym.R[0].Type != objabi.R_AMD64_TLS_GD || sym.R[0].Siz != 4 {
							t.Fatalf("TLS relocations = %+v", sym.R)
						}
					})
				}
			}
		}
	}
}
